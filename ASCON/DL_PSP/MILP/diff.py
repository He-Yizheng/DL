    def search(self):
        groups = {}
        for input in range(1, 32):
            self.make_model(input)
            last_round, p = self.solve_model()
            if last_round is not None:
                key = tuple((i, v) for i, v in last_round)
                if key not in groups:
                    groups[key] = [[], last_round]
                groups[key][0].append([input, p])
        os.remove(self.file)
        result = []
        for pairs, pattern in groups.values():
            min_p = min(p for _, p in pairs)
            result.append([[[n, p] for n, p in pairs if p == min_p], pattern])
        return result
        
        
