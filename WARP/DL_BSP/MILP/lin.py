    def minimize(self):
        file = open(self.file, "w")
        file.write("Minimize\n")
        temp = []
        for r in range(self.round):
            for i in range(16):
                temp.append("2 p0_%d_%d + p1_%d_%d " % (r, i, r, i))
                temp.append("+ ")
        temp.pop()
        for t in temp:
            file.write(t)
        file.write("\n")
        file.close()
    
    def subject_to(self):
        file = open(self.file, "a")
        file.write("Subject To\n")
        x = [[0 for _ in range(4)] for _ in range(32)]
        for j in range(4):
            x[self.inputcell][j] = (self.inputval >> (3 - j)) & 1
        for i in range(32):
            for j in range(4):
                file.write("x_0_%d_%d = %d\n" % (i, j, x[i][j]))
        
    def sbox_layer(self, x):
        file = open(self.file, "a")
        x_sb = [["x_%d_%d_%d_sb" % (self.rounds, i, j) for j in range(4)] for i in range(16)]
        p0 = ["p0_%d_%d" % (self.rounds, i) for i in range(16)]
        p1 = ["p1_%d_%d" % (self.rounds, i) for i in range(16)]
        for i in range(16):
            for j in self.sbox:
                file.write("%s %s %s %s %s %s %s %s %s %s %s %s %s %s %s %s %s %s %s %s >= %d\n" % (
                    j[0], x[i *2][0], j[1], x[i *2][1], j[2], x[i *2][2], j[3], x[i *2][3],
                    j[4], x_sb[i][0], j[5], x_sb[i][1], j[6], x_sb[i][2], j[7], x_sb[i][3],
                    j[8], p0[i], j[9], p1[i], j[10]
                ))
        file.close()
        return x_sb
    
    def xor_layer(self, x, x_sb):
        file = open(self.file, "a")
        x_n = [["x_%d_%d_%d" % (self.rounds + 1, i, j) for j in range(4)] for i in range(32)]
        for i in range(16):
            for j in range(4):
                for k in self.xor:
                    file.write("%s %s %s %s %s %s >= %d\n" % (
                        k[0], x[i * 2 + 1][j], k[1], x_sb[i][j], k[2], x_n[self.permutation[i * 2 + 1]][j], k[3]
                    ))
        for i in range(16):
            for j in range(4):
                file.write("%s - %s = 0\n" % (x_n[self.permutation[i * 2]][j], x[i * 2][j]))
        file.close()
        return x_n
    
    def binary(self):
        file = open(self.file, "a")
        file.write("Binary\n")
        for r in range(self.round + 1):
            for i in range(32):
                for j in range(4):
                    file.write("x_%d_%d_%d\n" % (r, i, j))
        for r in range(self.round):
            for i in range(16):
                for j in range(4):
                    file.write("x_%d_%d_%d_sb\n" % (r, i, j))
        file.close()
    
    def make(self):
        self.minimize()
        self.subject_to()
        x = [["x_0_%d_%d" % (i, j) for j in range(4)] for i in range(32)]
        for self.rounds in range(self.round):
            x_sb = self.sbox_layer(x)
            x = self.xor_layer(x, x_sb)
        self.binary()
        
    def solve(self):
        m = read(self.file)
        m.setParam(GRB.Param.Threads, 32)
        m.setParam("OutputFlag", 0)
        m.optimize()

        if m.Status != 2:
            return None, None

        x0 = [0] * 32
        for j in range(32):
            val = 0
            for k in range(4):
                val = (val << 1) | int(m.getVarByName("x_%d_%d_%d" % (self.round, j, k)).X)
            x0[j] = val

        output_hex = "".join("%x" % v for v in x0)
        return int(m.ObjVal), output_hex

